class AuthResult {
    private boolean success;
    private String message;
    private AuthUserView user;

    public static AuthResult success(String message, AuthUserView user) {
        AuthResult result = new AuthResult();
        result.setSuccess(true);
        result.setMessage(message);
        result.setUser(user);
        return result;
    }

    public boolean isSuccess() {
        return success;
    }

    public void setSuccess(boolean success) {
        this.success = success;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }

    public AuthUserView getUser() {
        return user;
    }

    public void setUser(AuthUserView user) {
        this.user = user;
    }
}

class AuthUserView {
    private long id;
    private String name;
    private String phone;
    private String role;
    private String level;
    private String avatar;

    public static AuthUserView fromStoredUser(StoredUser user) {
        AuthUserView view = new AuthUserView();
        view.setId(user.getId());
        view.setName(user.getName());
        view.setPhone(user.getPhone());
        view.setRole(user.getRole());
        view.setLevel(user.getLevelName());
        view.setAvatar(user.getAvatar());
        return view;
    }

    public long getId() {
        return id;
    }

    public void setId(long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public String getLevel() {
        return level;
    }

    public void setLevel(String level) {
        this.level = level;
    }

    public String getAvatar() {
        return avatar;
    }

    public void setAvatar(String avatar) {
        this.avatar = avatar;
    }
}

